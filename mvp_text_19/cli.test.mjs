import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import {spawnSync} from 'node:child_process';
import {fileURLToPath} from 'node:url';
const cli=fileURLToPath(new URL('./cli.mjs',import.meta.url));
test('CLI persists, rejects illegal moves without changing save, forks and resumes',t=>{
  const dir=fs.mkdtempSync(path.join(os.tmpdir(),'text19-test-'));
  t.after(()=>{
    assert.equal(path.dirname(path.resolve(dir)),path.resolve(os.tmpdir()));
    assert.ok(path.basename(dir).startsWith('text19-test-'));
    fs.rmSync(dir,{recursive:true,force:true});
  });
  const save=path.join(dir,'run.json');
  const call=(...args)=>spawnSync(process.execPath,[cli,'--save',save,...args],{encoding:'utf8'});
  assert.equal(call('new','31001').status,0);
  const initial=fs.readFileSync(save,'utf8');
  assert.equal(call('new','31002').status,1);assert.equal(fs.readFileSync(save,'utf8'),initial);
  assert.equal(call('visit','2').status,1);assert.equal(fs.readFileSync(save,'utf8'),initial);
  assert.equal(call('visit','2','--reason','중앙').status,0);
  assert.equal(call('start','--reason','시작').status,0);
  const before=fs.readFileSync(save,'utf8');
  const dice=JSON.parse(before).state.battle.dice;
  assert.equal(dice.length,3);
  const preview=JSON.parse(call('preview').stdout);assert.equal(preview.preview.length,9);
  assert.deepEqual(preview.preview.filter(p=>p.companion==='c3').map(p=>[p.slot,p.die]),dice.map((value,i)=>[i+1,value]));
  const single=JSON.parse(call('검토','#C3','2').stdout).preview;
  assert.equal(single.slot,2);assert.equal(single.die,dice[1]);
  assert.equal(call('preview','c3').status,1);
  assert.equal(call('move','c3').status,1);
  assert.equal(call('move','c3','4').status,1);
  assert.equal(fs.readFileSync(save,'utf8'),before);
  assert.equal(call('choose','7','--reason','오류검사').status,1);assert.equal(fs.readFileSync(save,'utf8'),before);
  const fork=path.join(dir,'fork.json');assert.equal(call('fork',fork).status,0);
  const f=JSON.parse(fs.readFileSync(fork));assert.equal(f.group,'control');assert.deepEqual(f.state,JSON.parse(before).state);
  // Reopen an earlier single-die save without changing its already-revealed result.
  f.rule=f.state.version='text-19-v1.2';
  const key=Object.keys(f.state.rng).find(key=>key.includes('|유저굴림'));
  f.state.rng[key]=1;
  f.state.battle.die=dice[0];
  delete f.state.battle.dice;
  const oldSave=JSON.stringify(f);
  fs.writeFileSync(fork,oldSave);
  const oldCall=(...args)=>spawnSync(process.execPath,[cli,'--save',fork,...args],{encoding:'utf8'});
  const migrated=JSON.parse(oldCall('show').stdout).view;
  assert.deepEqual(migrated.battle.dice,dice);
  assert.equal(fs.readFileSync(fork,'utf8'),oldSave);
  assert.equal(oldCall('move','c1','3').status,0);
  const persisted=JSON.parse(fs.readFileSync(fork,'utf8'));
  assert.equal(persisted.rule,migrated.version);
  assert.equal(persisted.state.journal.filter(e=>e.type==='rules-upgraded').length,1);
  assert.equal(call('주사위','사용','#C3','2').status,0);
  assert.equal(JSON.parse(call('show').stdout).view.battle.turn,2);
  const drop=JSON.parse(fs.readFileSync(save,'utf8')).state.journal.filter(e=>e.type==='drop').at(-1);
  assert.deepEqual([drop.source,drop.slot,drop.die],['c3',2,dice[1]]);
  // Simulate interrupted Windows copy-back: the committed .next is authoritative.
  fs.copyFileSync(save,save+'.next');fs.writeFileSync(save+'.commit','');fs.writeFileSync(save,'partial');
  assert.equal(call('show').status,0);
  assert.equal(call('move','c1','3','--reason','복구 뒤 진행').status,0);
  assert.equal(fs.existsSync(save+'.commit'),false);assert.equal(fs.existsSync(save+'.lock'),false);
});
